-- V1: Core threat-intelligence schema

CREATE TABLE feed_source (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             source_key VARCHAR(80) NOT NULL UNIQUE,
                             display_name VARCHAR(150) NOT NULL,
                             feed_type VARCHAR(40) NOT NULL
                                 CHECK (feed_type IN (
                                                      'PHISHING_URLS',
                                                      'MALWARE_URLS',
                                                      'DOMAIN_REPUTATION',
                                                      'MIXED'
                                     )),
                             feed_url TEXT,
                             enabled BOOLEAN NOT NULL DEFAULT TRUE,
                             refresh_interval_seconds INTEGER NOT NULL DEFAULT 3600
                                 CHECK (refresh_interval_seconds > 0),
                             last_attempt_at TIMESTAMPTZ,
                             last_successful_sync_at TIMESTAMPTZ,
                             last_status VARCHAR(20) NOT NULL DEFAULT 'NEVER_RUN'
                                 CHECK (last_status IN (
                                                        'NEVER_RUN',
                                                        'SUCCESS',
                                                        'FAILED'
                                     )),
                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE feed_sync_run (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               source_id BIGINT NOT NULL
                                   REFERENCES feed_source(id) ON DELETE RESTRICT,
                               started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               completed_at TIMESTAMPTZ,
                               outcome VARCHAR(20) NOT NULL DEFAULT 'RUNNING'
                                   CHECK (outcome IN (
                                                      'RUNNING',
                                                      'SUCCESS',
                                                      'FAILED'
                                       )),
                               records_downloaded INTEGER NOT NULL DEFAULT 0
                                   CHECK (records_downloaded >= 0),
                               records_inserted INTEGER NOT NULL DEFAULT 0
                                   CHECK (records_inserted >= 0),
                               records_updated INTEGER NOT NULL DEFAULT 0
                                   CHECK (records_updated >= 0),
                               error_summary TEXT
);

CREATE TABLE threat_indicator (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  source_id BIGINT NOT NULL
                                      REFERENCES feed_source(id) ON DELETE RESTRICT,

                                  indicator_type VARCHAR(30) NOT NULL
                                      CHECK (indicator_type IN (
                                                                'EXACT_URL',
                                                                'HOSTNAME',
                                                                'REGISTRABLE_DOMAIN'
                                          )),

                                  normalized_value TEXT NOT NULL,
                                  normalized_value_hash CHAR(64) NOT NULL
                                      CHECK (normalized_value_hash ~ '^[0-9a-f]{64}$'),

    threat_type VARCHAR(40) NOT NULL
        CHECK (threat_type IN (
            'PHISHING',
            'MALWARE_DISTRIBUTION',
            'SCAM',
            'UNKNOWN'
        )),

    source_confidence INTEGER
        CHECK (
            source_confidence IS NULL
            OR source_confidence BETWEEN 0 AND 100
        ),

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN (
            'ACTIVE',
            'STALE',
            'REVOKED',
            'EXPIRED'
        )),

    first_seen_at TIMESTAMPTZ,
    last_seen_at TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_indicator_per_source
        UNIQUE (source_id, indicator_type, normalized_value_hash)
);

CREATE INDEX idx_indicator_lookup
    ON threat_indicator (
                         indicator_type,
                         normalized_value_hash,
                         status
        );

CREATE INDEX idx_indicator_source_status
    ON threat_indicator (source_id, status);

CREATE INDEX idx_feed_sync_source_time
    ON feed_sync_run (source_id, started_at DESC);

CREATE TABLE trusted_domain (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                domain VARCHAR(253) NOT NULL UNIQUE,
                                match_subdomains BOOLEAN NOT NULL DEFAULT FALSE,

                                approval_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                                    CHECK (approval_status IN (
                                                               'PENDING',
                                                               'APPROVED',
                                                               'REJECTED',
                                                               'REVOKED'
                                        )),

                                reason TEXT NOT NULL,
                                created_by VARCHAR(120),
                                approved_by VARCHAR(120),
                                approved_at TIMESTAMPTZ,
                                expires_at TIMESTAMPTZ,

                                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT ck_trusted_domain_lowercase
                                    CHECK (domain = LOWER(domain))
    );